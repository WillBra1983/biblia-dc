import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const require = createRequire(new URL('../functions/package.json', import.meta.url))
const { PDFDocument } = require('pdf-lib')
const JSZip = require('jszip')
const { gerarAmostraAutomatica } = require('./src/bibliotecaAmostraAutomatica.js')
const pdf = await PDFDocument.create()
for (let i = 1; i <= 100; i++) pdf.addPage([300, 400]).drawText(`Pagina ${i}`, { x: 30, y: 300 })
const original = await pdf.save()
const amostra = await gerarAmostraAutomatica(original, 'pdf', 10)
assert.equal((await PDFDocument.load(amostra.bytes)).getPageCount(), 10)
assert.equal((await PDFDocument.load(original)).getPageCount(), 100)
assert.equal(amostra.limite, 10)
const zip = new JSZip()
zip.file('mimetype', 'application/epub+zip')
zip.file('META-INF/container.xml', '<container><rootfiles><rootfile full-path="OEBPS/content.opf"/></rootfiles></container>')
zip.file('OEBPS/content.opf', '<package version="3.0" xmlns:dc="http://purl.org/dc/elements/1.1/"><metadata><dc:title>Teste</dc:title><dc:identifier>teste</dc:identifier></metadata><manifest><item id="a" href="a.xhtml" media-type="application/xhtml+xml"/><item id="b" href="b.xhtml" media-type="application/xhtml+xml"/></manifest><spine><itemref idref="a"/><itemref idref="b"/></spine></package>')
zip.file('OEBPS/a.xhtml', `<html xmlns="http://www.w3.org/1999/xhtml"><head><title>A</title></head><body><p>${'A'.repeat(100)}</p></body></html>`)
zip.file('OEBPS/b.xhtml', `<html xmlns="http://www.w3.org/1999/xhtml"><head><title>B</title></head><body><p>${'B'.repeat(100)}</p></body></html>`)
const epub = await gerarAmostraAutomatica(await zip.generateAsync({ type: 'nodebuffer' }), 'epub', 10)
const resultado = await JSZip.loadAsync(epub.bytes)
assert.equal(resultado.file('OEBPS/b.xhtml'), null, 'Capítulo fora da amostra não é enviado')
assert.equal(epub.limite, 20)
assert.ok((await resultado.file('OEBPS/a.xhtml').async('string')).includes('A'.repeat(20)))
assert.ok(!(await resultado.file('OEBPS/a.xhtml').async('string')).includes('A'.repeat(21)))
console.log('Amostra: PDF 100→10 páginas, original preservado, EPUB recortado e capítulo posterior ausente verificados.')
